SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED;

SELECT
	o.OrderId
FROM
	dbo.Orders AS o WITH (NOLOCK)
	INNER HASH JOIN dbo.Customer AS c WITH (INDEX(IX_Customer_Region), FORCESEEK) ON c.CustomerId = o.CustomerId
OPTION (MAXDOP 1, RECOMPILE);

SET ROWCOUNT 100;
DELETE FROM dbo.Log WHERE LoggedAt < '20200101';
SET ROWCOUNT 0;
GO
CREATE PROCEDURE dbo.Report
WITH RECOMPILE
AS
SET NOCOUNT ON;
SELECT r.ReportId FROM dbo.Report AS r WITH (READUNCOMMITTED);