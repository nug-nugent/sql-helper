CREATE FUNCTION dbo.NextNumber (@x INT)
RETURNS INT
AS
BEGIN
	RETURN @x + 1
END
GO

CREATE FUNCTION dbo.Numbers (@x INT)
RETURNS TABLE
AS
RETURN (SELECT @x AS x)
GO

CREATE OR ALTER TRIGGER dbo.WidgetChanged ON dbo.Widget AFTER UPDATE
AS
BEGIN
	SET NOCOUNT ON
	UPDATE dbo.Widget SET Changed = GETDATE() WHERE WidgetId IN (SELECT WidgetId FROM inserted)
END
GO

